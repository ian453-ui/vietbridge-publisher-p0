    const saved=await (await fetch(`${base}/api/facebook/accounts`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify(imported)})).json() as any;
    assert.equal((await fetch(`${base}/api/facebook/accounts/select`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({id:saved.id})})).status,200);
    const accountList=await (await fetch(`${base}/api/facebook/accounts`)).json() as any;assert.equal(accountList.selectedAccountId,saved.id);
    assert.match(page,/data-wechat-reconcile/);
    const facebookCandidates=await (await fetch(`${base}/api/content/candidates?platforms=facebook`)).json() as any;
    assert.equal(facebookCandidates.candidates.length,1);
    assert.equal(facebookCandidates.candidates[0].articleId,'Daily-018');
    const previewAsset=facebookCandidates.candidates[0].assets[0];
    const previewUrl=new URL('/api/content/asset',base);previewUrl.searchParams.set('path',previewAsset.path);previewUrl.searchParams.set('revision',previewAsset.revision);
    const previewResponse=await fetch(previewUrl);assert.equal(previewResponse.status,200);assert.equal(previewResponse.headers.get('x-asset-revision'),previewAsset.revision);
    assert.match(previewResponse.headers.get('cache-control')??'',/immutable/);
    const staleUrl=new URL(previewUrl);staleUrl.searchParams.set('revision','0'.repeat(64));assert.equal((await fetch(staleUrl)).status,409);
    const channelsCandidates=await (await fetch(`${base}/api/content/candidates?platforms=wechat_channels`)).json() as any;
    assert.equal(channelsCandidates.candidates.length,0);
    assert.equal((await fetch(`${base}/api/jobs/${jobId}/wechat-reconcile`,{method:'POST'})).status,409);
    writeFileSync(join(contentRoot,"Daily-018-wechat-companion-public.md"),"# 公众号测试标题\n公开正文");
    const wechat = await fetch(`${base}/api/tasks/execute`,{method:"POST",headers:{"content-type":"application/json"},body:JSON.stringify({mode:"article_id",value:"Daily-018",platforms:["wechat_official_account"]})});
    assert.equal(wechat.status,201);
    const wechatBatch = await wechat.json() as any;
    assert.equal(wechatBatch.jobs[0].platform,"wechat_official_account");
    assert.equal(wechatBatch.control_state,"AWAITING_APPROVAL");
    const manualDeleteDb=openDatabase(dbPath);
    manualDeleteDb.prepare("UPDATE jobs SET state='DRAFT_API_WRITTEN_NOT_PUBLISHED' WHERE job_id=?").run(wechatBatch.jobs[0].job_id);
    manualDeleteDb.close();
    const existingDraft=await fetch(`${base}/api/tasks/execute`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({mode:'article_id',value:'Daily-018',platforms:['wechat_official_account']})});
    assert.equal(existingDraft.status,409);
    assert.match(JSON.stringify(await existingDraft.json()),/已有发布记录或公众号草稿/);
    const draftCandidate=await (await fetch(`${base}/api/content/candidates?platforms=xiaohongshu&includeIncomplete=1`)).json() as any;
    assert.deepEqual(draftCandidate.candidates.find((x:any)=>x.articleId==='Daily-018').draftPlatforms,['wechat_official_account']);
    const manualDeleted=await fetch(`${base}/api/jobs/${wechatBatch.jobs[0].job_id}/wechat-manual-deleted`,{method:'POST'});
    assert.equal(manualDeleted.status,200);
    const manualDeletedBatch=await manualDeleted.json() as any;
    assert.equal(manualDeletedBatch.jobs[0].state,'PLATFORM_DELETED');
    const created = await fetch(`${base}/api/tasks/execute`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ mode: "article_id", value: "Daily-018", platforms: ["xiaohongshu", "facebook"] }) });
