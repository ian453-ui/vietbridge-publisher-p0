    const resumedBatch=await resumed.json() as any;
    assert.equal(resumedBatch.control_state,'AWAITING_APPROVAL');
    assert.equal(resumedBatch.pause_requested,0);
    assert.equal(resumedBatch.jobs.find((j:any)=>j.platform==='facebook').state,'READY_FOR_USER_APPROVAL');
    assert.equal(resumedBatch.jobs.find((j:any)=>j.job_id===retryId).state,'FAILED_PREFLIGHT');
