    const batch = await created.json() as any;
    assert.equal(batch.jobs.length, 2);
    assert.equal(batch.control_state, "AWAITING_APPROVAL");
    const failureDb=openDatabase(dbPath);
    failureDb.prepare("UPDATE jobs SET state='FAILED_PREFLIGHT' WHERE batch_id=?").run(batch.batch_id);
    failureDb.prepare("UPDATE publication_batches SET control_state='COMPLETED' WHERE batch_id=?").run(batch.batch_id);
    const beforeCount=(failureDb.prepare('SELECT COUNT(*) AS n FROM publication_batches').get() as any).n;
    const recreated=await (await fetch(`${base}/api/tasks/execute`,{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({mode:'article_id',value:'Daily-018',platforms:['xiaohongshu','facebook']})})).json() as any;
    assert.equal(recreated.batch_id,batch.batch_id);
    assert.equal(recreated.control_state,'AWAITING_APPROVAL');
    assert.ok(recreated.jobs.every((j:any)=>j.state==='READY_FOR_USER_APPROVAL'));
    assert.equal((failureDb.prepare('SELECT COUNT(*) AS n FROM publication_batches').get() as any).n,beforeCount);
    failureDb.close();
