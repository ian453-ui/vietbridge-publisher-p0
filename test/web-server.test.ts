    const shown = await (await fetch(`${base}/api/batches`)).json() as any;
    const failed = shown.batches[0].jobs.find((j:any)=>j.job_id===retryId);
    assert.match(failed.failure_reason, /小红书本地服务/);
    assert.equal(failed.can_retry, true);
    assert.equal(failed.can_resume_stopped,true);
    assert.equal((await fetch(`${base}/api/jobs/${retryId}/retry`,{method:'POST'})).status,200);
    assert.equal((await fetch(`${base}/api/jobs/${retryId}/retry`,{method:'POST'})).status,409);
    new PublisherStore(editDb).transition(retryId,'FAILED_PREFLIGHT',{error:'timeout'});
    editDb.prepare("UPDATE jobs SET submit_safety_domain='MAY_HAVE_SUBMITTED' WHERE job_id=?").run(retryId);
    editDb.prepare("UPDATE publication_batches SET control_state='COMPLETED' WHERE batch_id=?").run(batch.batch_id);
    assert.equal((await fetch(`${base}/api/jobs/${retryId}/retry`,{method:'POST'})).status,409);
    editDb.close();
    assert.equal((await fetch(`${base}/api/batches/${batch.batch_id}/stop`,{method:'POST'})).status,200);
    const stopped = await (await fetch(`${base}/api/batches`)).json() as any;
    assert.equal(stopped.batches[0].control_state,'TERMINATED');
    const resumed=await fetch(`${base}/api/batches/${batch.batch_id}/resume`,{method:'POST'});
